"""PLUMB's numbers, worked out once here (the FM-1 has no floating point) and written into
firmware/gen/plumb_tables.h: a sine, pitch tables, the LFO rates, the ENV times, the DAMP factors."""

import math
from pathlib import Path

root = Path(__file__).resolve().parent.parent
FS = 44100
out = ["/* Generated by tools/gen_tables.py: do not edit. */", "#pragma once", ""]


def table(ctype, name, values, per_line=12):
    out.append(f"static const {ctype} {name}[{len(values)}] = {{")
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    out.append("};")


# --- one sine cycle, 1024 points (+1 for the interpolation), full scale 32767
table("int16_t", "sine1k", [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)], 16)
out.append("")

# --- pitch: phase increments (2^32 = one cycle a sample) of C9 .. B9 (MIDI 120..131); lower octaves shift right
table("uint32_t", "inc_c9", [round(440 * 2 ** ((120 + k - 69) / 12) * 2 ** 32 / FS) for k in range(12)], 6)
out.append("")

# --- LFO RATE: 64 steps, 0.01 Hz .. 20 Hz; the phase step a block of 16 frames (2^32 = one cycle), and 1/100 Hz
rates = [0.01 * 2000 ** (i / 63) for i in range(64)]
table("uint32_t", "lfo_inc16", [round(f * 16 * 2 ** 32 / FS) for f in rates], 8)
table("uint16_t", "lfo_hundredths", [round(f * 100) for f in rates], 16)
out.append("#define LFO_RATES 64u")
# --- ENV times, ms
env = [0, 2, 5, 10, 20, 30, 50, 70, 100, 130, 160, 200, 250, 300, 400, 500, 600, 800, 1000, 1200, 1500, 1800,
       2000, 2500, 3000, 3500, 4000, 5000, 6000, 8000, 10000, 15000, 20000]
table("uint16_t", "env_ms", env, 12)
out.append(f"#define ENV_STEPS {len(env)}u")
out.append("")
# --- DAMP: the swing falls to 1 % (-40 dB) in N cycles. The factor (Q16) is applied 64 times a cycle.
damp = [0, 1, 2, 3, 4, 6, 8, 12, 16, 24, 32]
table("uint8_t", "damp_cycles", damp, 11)
table("uint16_t", "damp_q16", [65535 if n == 0 else round(65536 * 0.01 ** (1 / (64 * n))) for n in damp], 11)
out.append(f"#define DAMPS {len(damp)}u")
out.append("")
(root / "firmware/gen/plumb_tables.h").write_text("\n".join(out) + "\n")
print("firmware/gen/plumb_tables.h written")
