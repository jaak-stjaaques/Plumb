"""Draw PLUMB's boot logo (twelve plumb bobs on lines of falling length, caught mid-swing in a pendulum wave) and
pack it into a small RGB565 run-length bitmap: assets/plumb-boot.png (240 x 240), assets/logo.png (480 x 480) and
firmware/gen/plumb_boot_logo.h (what the firmware draws)."""

import math
from itertools import groupby
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFont

root = Path(__file__).resolve().parent.parent
S = 4                                   # drawn 4x larger, then shrunk: smooth edges
BG = (10, 16, 22)                       # the firmware's C_BG
BOB = (226, 176, 84)                    # C_BOB: brass, the bobs, the notes
TIME = (122, 168, 240)                  # C_TIME: chalk blue, the swing
KEY = (236, 232, 222)                   # C_KEY
RULE = (44, 58, 68)


def mix(c, a):
    return tuple(round(BG[i] + (c[i] - BG[i]) * a) for i in range(3))


img = Image.new("RGB", (240 * S, 240 * S), BG)
d = ImageDraw.Draw(img)
N, X0, X1, TOP = 12, 32, 208, 34
d.line([(X0 - 12) * S, TOP * S, (X1 + 12) * S, TOP * S], fill=KEY, width=3 * S)      # the beam
t = 0.062                               # a moment of the cycle: the snake
bobs = []
for k in range(N):
    px = X0 + k * (X1 - X0) / (N - 1)
    length = 118 - k * 5.2              # the long, slow ones on the left
    n = 6 + k
    swing = math.cos(2 * math.pi * n * t) * 0.17          # radians
    bx, by = px + math.sin(swing) * length, TOP + math.cos(swing) * length
    bobs.append((px, bx, by, swing))
# the longest one's path: an arc in chalk blue
px, _, _, _ = bobs[0]
r = 118
d.arc([(px - r) * S, (TOP - r) * S, (px + r) * S, (TOP + r) * S], start=90 - 11, end=90 + 11,
      fill=mix(TIME, 0.45), width=2 * S)
for i, (px, bx, by, swing) in enumerate(bobs):
    d.line([px * S, TOP * S, bx * S, by * S], fill=mix(KEY, 0.55), width=1 * S)
for i in range(N - 1):                  # the snake through the bobs
    d.line([bobs[i][1] * S, bobs[i][2] * S, bobs[i + 1][1] * S, bobs[i + 1][2] * S], fill=mix(TIME, 0.8), width=1 * S)
for px, bx, by, swing in bobs:          # a plumb bob: a brass drop, its point down the line
    rr = 5.2
    ux, uy = math.sin(swing), math.cos(swing)
    tip = (bx + ux * rr * 2.0, by + uy * rr * 2.0)
    side = (uy * rr, -ux * rr)
    d.polygon([((bx + side[0]) * S, (by + side[1]) * S), ((bx - side[0]) * S, (by - side[1]) * S), (tip[0] * S, tip[1] * S)],
              fill=BOB)
    d.ellipse([(bx - rr) * S, (by - rr) * S, (bx + rr) * S, (by + rr) * S], fill=BOB)
font = ImageFont.truetype(str(root / "assets/fonts/IBMPlexMono-Medium.ttf"), 22 * S)
text = "P L U M B"
w = d.textlength(text, font=font)
d.text(((240 * S - w) / 2, 172 * S), text, font=font, fill=KEY)
image = img.resize((240, 240), Image.LANCZOS)
image = image.quantize(colors=28, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert("RGB")
image.save(root / "assets/plumb-boot.png")
image.resize((480, 480), Image.NEAREST).save(root / "assets/logo.png")

background = Image.new("RGB", image.size, image.getpixel((0, 0)))
left, top, right, bottom = ImageChops.difference(image, background).getbbox()


def rgb565(pixel):
    red, green, blue = pixel
    return ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)


pixels = map(rgb565, image.crop((left, top, right, bottom)).getdata())
runs = []
for colour, group in groupby(pixels):
    n = sum(1 for _ in group)
    while n > 65535:
        runs.append((65535, colour))
        n -= 65535
    runs.append((n, colour))
lines = []
for start in range(0, len(runs), 6):
    lines.append("    " + ", ".join(f"{count}, 0x{colour:04x}" for count, colour in runs[start:start + 6]) + ",")
header = (
    "/* Generated by tools/gen_boot_logo.py (assets/plumb-boot.png). */\n"
    f"#define BOOT_LOGO_X {left}u\n"
    f"#define BOOT_LOGO_Y {top}u\n"
    f"#define BOOT_LOGO_WIDTH {right - left}u\n"
    f"#define BOOT_LOGO_HEIGHT {bottom - top}u\n"
    "static const uint16_t boot_logo_runs[] = {\n"
    + "\n".join(lines) + "\n};\n"
)
(root / "firmware/gen/plumb_boot_logo.h").write_text(header)
print(f"{len(runs)} runs, box {left},{top} {right - left}x{bottom - top}")
