"""Generate the FM-1 menu bitmaps from the bundled IBM Plex Mono TTF."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


root = Path(__file__).resolve().parent.parent
source = root / "assets/fonts/IBMPlexMono-Medium.ttf"


def c_array(name, values, kind="uint8_t", columns=16):
    rows = [", ".join(str(n) for n in values[i:i + columns])
            for i in range(0, len(values), columns)]
    return f"static const {kind} {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def font_at(name, size):
    font = ImageFont.truetype(source, size)
    glyphs = [chr(code) for code in range(32, 127)]
    boxes = [font.getbbox(ch) for ch in glyphs]
    top = min(box[1] for box in boxes)
    height = max(box[3] for box in boxes) - top
    assert min(box[0] for box in boxes) >= 0
    advance = round(font.getlength("M"))
    widths, offsets, data = [], [], []
    for ch, box in zip(glyphs, boxes):
        width = (max(1, box[2]) + 1) & ~1
        glyph = Image.new("L", (width, height))
        ImageDraw.Draw(glyph).text((0, -top), ch, font=font, fill=255)
        pixels = [(value + 8) // 17 for value in glyph.tobytes()]
        widths.append(width)
        offsets.append(len(data))
        data.extend((hi << 4) | lo for hi, lo in zip(pixels[::2], pixels[1::2]))
    return "\n".join((
        c_array(name + "_ADV", [advance] * len(glyphs)),
        c_array(name + "_WIDTH", widths),
        c_array(name + "_OFF", offsets, "uint16_t"),
        c_array(name + "_DATA", data),
        f"static const felucca_font_t {name} = {{{height}, 0, 32, 126, "
        f"{name}_ADV, {name}_WIDTH, {name}_OFF, {name}_DATA}};\n",
    ))


header = "/* Generated by tools/gen_ui_font.py from IBM Plex Mono Medium (OFL 1.1). */\n#pragma once\n\n"
header += "\n".join(font_at(name, size) for name, size in (("UI_SMALL", 12), ("UI_BODY", 16), ("UI_LARGE", 18)))
(root / "firmware/gen/ui_font.h").write_text(header)
